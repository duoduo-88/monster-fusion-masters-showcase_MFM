"""Build the local bilingual section index from the public articles."""
from html.parser import HTMLParser
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1] / "docs"
PAGES = ("index.html", "rules.html", "modes.html", "history.html")


class Article(HTMLParser):
    def __init__(self, path):
        super().__init__()
        self.in_main = False
        self.section = None
        self.heading = None
        self.title = ""
        self.sections = {}
        self.feed(path.read_text(encoding="utf-8"))

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "main":
            self.in_main = True
        if not self.in_main:
            return
        if tag == "section" and attrs.get("id"):
            self.section = {"heading": "", "parts": []}
            self.sections[attrs["id"]] = self.section
        if tag in ("h1", "h2"):
            self.heading = tag

    def handle_endtag(self, tag):
        if tag == "main":
            self.in_main = False
        if tag == "section":
            self.section = None
        if tag == self.heading:
            self.heading = None

    def handle_data(self, data):
        if not self.in_main or self.section is None:
            return
        self.section["parts"].append(data)
        if self.heading:
            self.section["heading"] += data
        if self.heading == "h1":
            self.title += data


def build():
    records = []
    for page in PAGES:
        articles = {lang: Article(ROOT / folder / page)
                    for lang, folder in (("zh-Hant", ""), ("en", "en"))}
        assert articles["zh-Hant"].sections.keys() == articles["en"].sections.keys(), page
        for section_id in articles["zh-Hant"].sections:
            variants = {}
            for lang, article in articles.items():
                section = article.sections[section_id]
                variants[lang] = {
                    "title": article.title.strip(),
                    "heading": section["heading"].strip(),
                    "text": " ".join(" ".join(section["parts"]).split()),
                }
            records.append({"page": page, "id": section_id, "variants": variants})
    return "/* Generated by scripts/build-search-index.py; edit the articles instead. */\nwindow.MFMWikiSearchIndex = " + json.dumps(records, ensure_ascii=False, separators=(",", ":")) + ";\n"


if __name__ == "__main__":
    output = ROOT / "wiki-search-index.js"
    generated = build()
    if "--check" in sys.argv:
        if not output.exists() or output.read_text(encoding="utf-8") != generated:
            raise SystemExit("Search index is stale: run python scripts/build-search-index.py")
        print("Search index matches all bilingual article sections.")
    else:
        output.write_text(generated, encoding="utf-8")
        print(f"Built {output.name}")
